/**
 * Returns an HSL color string for a team/option label, or null if unknown.
 */
export function getTeamColor(label: string): string | null {
  const lower = label.toLowerCase();
  for (const [keyword, color] of Object.entries(TEAM_COLORS)) {
    if (lower.includes(keyword)) return color;
  }
  return null;
}
